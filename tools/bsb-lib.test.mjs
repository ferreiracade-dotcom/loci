import { describe, expect, it } from 'vitest'
import { deflateRawSync } from 'node:zlib'
import { loadBooks, makeBookResolver, parseUsfmBook, parseBlb, parseInterlinear, parseTopics, parseSharedStrings, readZip, stripUsfmInline } from './bsb-lib.mjs'
import { stringifyBible } from './bsb-usfm-to-json.mjs'

const resolver = makeBookResolver()

describe('book codes', () => {
  it('reads the app table and maps names, abbreviations and BSB spellings', () => {
    expect(loadBooks()).toHaveLength(66)
    expect(resolver.byName('John')).toBe('JHN')
    expect(resolver.byName('Psalm')).toBe('PSA')
    expect(resolver.byName('Song of Solomon')).toBe('SNG')
    expect(resolver.byName('1 Thessalonians')).toBe('1TH')
    expect(resolver.byCode('NAM')).toBe('NAM')
  })
  it('fails loudly on an unmapped book', () => {
    expect(() => resolver.byName('Tobit')).toThrow(/unmapped book name/)
    expect(() => resolver.byCode('TOB')).toThrow(/unmapped book code/)
  })
})

const MATT = String.raw`\id MAT Autogenerated BSB by bsb2usfm
\h Matthew
\mt1 Matthew
\c 17
\s1 The Transfiguration
\r (\ref Mark 9:2–8|MRK 9:2-8\ref*)
\p \v 19 Then the disciples came to Jesus privately. \v 20 He answered, \wj “Nothing will be impossible for you.”\wj*\f + \fr 17:20 \ft BYZ and TR include \fqa \fv 21\fv*But this kind\ft ; see \ref Mark 9:29|MRK 9:29\ref*.\f*
\s1 The Second Prediction of the Passion
\r (\ref Mark 9:30–32|MRK 9:30-32\ref*)
\p \v 22 When they gathered together in Galilee, Jesus said,
\q1 \v 23 “They will kill Him.”
\q2 and “He will rise.”
\c 18
\p \v 1 At that time \v 2 He called a child.`

describe('parseUsfmBook', () => {
  const { code, chapters } = parseUsfmBook(MATT)
  it('maps the \\id to the app book code', () => {
    expect(code).toBe('MAT')
    expect(resolver.byCode(code)).toBe('MAT')
  })
  it('keeps the source verse numbers, including a missing verse (no 21)', () => {
    expect(chapters[17].map((v) => v[0])).toEqual([19, 20, 22, 23])
    expect(chapters[18].map((v) => v[0])).toEqual([1, 2])
  })
  it('strips headings, cross-reference lines, footnote bodies and markup', () => {
    expect(chapters[17][1][1]).toBe('He answered, “Nothing will be impossible for you.”')
    expect(JSON.stringify(chapters)).not.toMatch(/[\\]|Transfiguration|Mark 9|BYZ/)
  })
  it('joins poetry lines and keeps typographic quotes', () => {
    expect(chapters[17][3][1]).toBe('“They will kill Him.” and “He will rise.”')
  })
  it('splits several verses on one line', () => {
    expect(chapters[18]).toEqual([[1, 'At that time'], [2, 'He called a child.']])
  })
  it('stripUsfmInline removes nested footnote references', () => {
    expect(stripUsfmInline(String.raw`good\f + \fr 1:1 \ft see \ref Gen 1:1|GEN 1:1\ref*.\f* news`)).toBe('good news')
  })
})

describe('parseBlb', () => {
  const text = [
    'The Holy Bible, Berean Standard Bible, BLB is produced in cooperation with ...',
    'This text of God\'s Word has been dedicated to the public domain.\t',
    'Verse\tBerean Literal Bible (Draft)',
    'Psalm 3:1\tA Psalm of David.',
    'Matthew 17:20\tHe says, “[It is] small.”',
    'Matthew 17:21\t',
    'Matthew 17:22\tAnd while they were gathering'
  ].join('\n')
  it('parses pairs, keeps [supplied] brackets, drops blank verses and headers', () => {
    const blb = parseBlb(text, resolver)
    expect(blb.PSA[3]).toEqual([[1, 'A Psalm of David.']])
    expect(blb.MAT[17]).toEqual([[20, 'He says, “[It is] small.”'], [22, 'And while they were gathering']])
  })
  it('fails loudly on an unknown book', () => {
    expect(() => parseBlb('Tobit 1:1\tx', resolver)).toThrow(/unmapped/)
  })
})

describe('parseInterlinear', () => {
  const H = Array(23).fill('')
  H[0] = 'Heb Sort'; H[1] = 'Greek Sort'; H[2] = 'BSB Sort'; H[4] = 'Language'; H[7] = 'Translit'; H[10] = 'Str Heb'; H[11] = 'Str Grk'; H[12] = 'VerseId'; H[18] = ' BSB version '
  const row = (f) => { const r = Array(23).fill(''); for (const [i, v] of Object.entries(f)) r[i] = v; return r.join('\t') }
  const tsv = [
    H.join('\t'),
    row({ 0: 1, 1: 0, 2: 1, 4: 'Hebrew', 5: 'בְּרֵאשִׁ֖ית', 7: 'bə·rê·šîṯ', 8: 'Prep-b | N-fs', 10: '7225', 12: 'Genesis 1:1', 18: ' In the beginning ' }),
    row({ 0: 3, 1: 0, 2: 2, 4: 'Hebrew', 5: 'אֱלֹהִ֑ים', 8: 'N-mp', 10: '430', 18: ' God ' }),
    row({ 0: 2, 1: 0, 2: 3, 4: 'Hebrew', 5: 'בָּרָ֣א', 8: 'V-Qal-Perf-3ms', 10: '1254', 18: ' created ' }),
    row({ 0: 4, 1: 0, 2: 4, 4: 'Hebrew' }), // padding
    row({ 0: 5, 1: 0, 2: 5, 4: 'Hebrew', 12: 'Genesis 1:2', 5: 'וְהָאָ֗רֶץ', 10: '776', 18: ' And the earth ' }),
    row({ 0: 999999, 1: 2, 2: 6, 4: 'Greek', 5: 'Θεὸς', 8: 'N-NMS', 11: '2316', 12: 'John 1:1', 18: ' God ' }),
    row({ 0: 999999, 1: 1, 2: 7, 4: 'Greek', 5: 'Λόγος', 8: 'N-NMS', 11: '3056', 18: ' Word ' }),
    row({ 0: 999999, 1: 9, 2: 8, 4: 'Greek' }) // padding
  ].join('\n')
  const il = parseInterlinear(tsv, resolver)
  it('groups by book code, chapter and verse and skips padding rows', () => {
    expect(Object.keys(il).sort()).toEqual(['GEN', 'JHN'])
    expect(il.GEN[1][1]).toHaveLength(3)
    expect(il.GEN[1][2]).toHaveLength(1)
    expect(il.JHN[1][1]).toHaveLength(2)
  })
  it('emits original-language reading order (Heb Sort / Greek Sort), not English order', () => {
    expect(il.GEN[1][1].map((w) => w.e)).toEqual(['In the beginning', 'created', 'God'])
    expect(il.JHN[1][1].map((w) => w.e)).toEqual(['Word', 'God'])
  })
  it('prefixes Strong\'s numbers and trims the English', () => {
    expect(il.GEN[1][1][0]).toEqual({ o: 'בְּרֵאשִׁ֖ית', t: 'bə·rê·šîṯ', s: 'H7225', p: 'Prep-b | N-fs', e: 'In the beginning' })
    expect(il.JHN[1][1][1].s).toBe('G2316')
  })
  it('rejects a table whose columns moved', () => {
    expect(() => parseInterlinear(tsv.replace('Str Heb', 'X'), resolver)).toThrow(/column 10/)
  })
})

describe('topical index', () => {
  const strings = parseSharedStrings('<sst><si><t>Aaron: Age of</t></si><si><t>Exodus 7:7</t></si><si><r><t>Numbers </t></r><r><t>33:38</t></r></si><si><t>Sort</t></si><si><t>Topic</t></si><si><t>R&amp;D</t></si></sst>')
  const sheet =
    '<sheetData><row r="3"><c r="A3" t="s"><v>3</v></c><c r="C3" t="s"><v>4</v></c></row>' +
    '<row r="4"><c r="A4"><v>1</v></c><c r="C4" t="s"><v>0</v></c></row>' +
    '<row r="5"><c r="A5"><v>2</v></c><c r="E5" t="s"><v>1</v></c><c r="F5" t="s"><v>5</v></c></row>' +
    '<row r="6"><c r="E6" t="s"><v>2</v></c></row>' +
    '<row r="7"><c r="E7" t="s"><v>1</v></c></row>' +
    '<row r="8"><c r="C8"><v>666</v></c></row></sheetData>'
  it('reads shared strings with rich-text runs and entities', () => {
    expect(strings[2]).toBe('Numbers 33:38')
    expect(strings[5]).toBe('R&D')
  })
  it('groups verse rows under their topic, drops duplicates and empty topics, keeps ref strings', () => {
    expect(parseTopics(sheet, strings)).toEqual({ 'Aaron: Age of': ['Exodus 7:7', 'Numbers 33:38'] })
  })
})

describe('readZip', () => {
  it('reads stored and deflated entries', () => {
    const entry = (name, data, method) => {
      const nameB = Buffer.from(name)
      const comp = method === 8 ? deflateRawSync(data) : data
      const lh = Buffer.alloc(30)
      lh.writeUInt32LE(0x04034b50, 0); lh.writeUInt16LE(method, 8); lh.writeUInt32LE(comp.length, 18); lh.writeUInt32LE(data.length, 22); lh.writeUInt16LE(nameB.length, 26)
      return { name: nameB, comp, data, method, local: Buffer.concat([lh, nameB, comp]) }
    }
    const es = [entry('a.txt', Buffer.from('hello'), 0), entry('d/b.txt', Buffer.from('world '.repeat(20)), 8)]
    let off = 0
    const cds = es.map((e) => {
      const cd = Buffer.alloc(46)
      cd.writeUInt32LE(0x02014b50, 0); cd.writeUInt16LE(e.method, 10); cd.writeUInt32LE(e.comp.length, 20); cd.writeUInt32LE(e.data.length, 24); cd.writeUInt16LE(e.name.length, 28); cd.writeUInt32LE(off, 42)
      off += e.local.length
      return Buffer.concat([cd, e.name])
    })
    const cd = Buffer.concat(cds)
    const eocd = Buffer.alloc(22)
    eocd.writeUInt32LE(0x06054b50, 0); eocd.writeUInt16LE(es.length, 10); eocd.writeUInt32LE(cd.length, 12); eocd.writeUInt32LE(off, 16)
    const zip = readZip(Buffer.concat([...es.map((e) => e.local), cd, eocd]))
    expect(zip.get('a.txt')().toString()).toBe('hello')
    expect(zip.get('d/b.txt')().toString()).toBe('world '.repeat(20))
  })
})

describe('stringifyBible', () => {
  it('writes one book per line in canonical order', () => {
    const out = stringifyBible({ MAT: { 1: [[1, 'x']] }, GEN: { 1: [[1, 'y']] } }, ['GEN', 'EXO', 'MAT'])
    expect(JSON.parse(out)).toEqual({ GEN: { 1: [[1, 'y']] }, MAT: { 1: [[1, 'x']] } })
    expect(out.split('\n')).toHaveLength(5)
  })
})
